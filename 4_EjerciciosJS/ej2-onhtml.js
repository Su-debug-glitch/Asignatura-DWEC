function eventOnKeyPress(input) {
    input.style.backgroundColor = "lightpink";
}

function eventOnKeyUp(input) {
    input.style.backgroundColor = "lightblue";
    input.style.borderColor = "lightgray";
}

function eventOnFocus(input) {
    input.style.backgroundColor = "lightyellow";
}

function eventOnBlur(input) {
    input.style.backgroundColor = "brown";
}

function eventOnSelect(input) {
    input.style.backgroundColor = "lightcoral";
}